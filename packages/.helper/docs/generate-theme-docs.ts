interface ThemeDoc {
  id: string;
  title: string;
  npmName: string;
  exportName: string;
  dark: boolean;
  family: string | undefined;
  extension: Extension;
  css: string;
  foreground: Rgba;
  /** Background, then the active line and the selection composited over it. */
  surfaces: Array<[string, Rgba]>;
  highlights: Record<string, string>;
  mergeStyles: Record<string, string>;
}

function docsVersion(): string {
  const index = process.argv.indexOf('--version');
  if (index >= 0) {
    const version = process.argv[index + 1];
    if (!version || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error('--version expects x.y.z');
    return version;
  }
  const versions = fs
    .readdirSync(docsRoot)
    .filter((name) => /^\d+\.\d+\.\d+$/.test(name))
    .map((name) => ({ name, parts: name.split('.').map(Number) }))
    .sort((a, b) => a.parts[0] - b.parts[0] || a.parts[1] - b.parts[1] || a.parts[2] - b.parts[2]);
  const latest = versions.at(-1);
  if (!latest) throw new Error(`No docs/<x.y.z> folder found in ${docsRoot}`);
  return latest.name;
}

const formatRatio = (value: number) => `${value.toFixed(2)}:1`;
const code = (value: string) => `\`${value}\``;
const yamlList = (values: string[]) => `[ ${values.map((value) => JSON.stringify(value)).join(', ')} ]`;
const verdict = (value: number | undefined, min: number) =>
  value === undefined ? '-' : value >= min ? 'Pass' : `Below ${min}:1`;
/** Declaration lookup by name (keeps index-signature access explicit). */
const prop = (decls: Record<string, string> | undefined, name: string) => decls?.[name];
const mode = (doc: ThemeDoc) => (doc.dark ? 'Dark' : 'Light');
const surface = (doc: ThemeDoc, name: string) => doc.surfaces.find(([key]) => key === name)?.[1];

function frontmatter(fields: {
  label: string;
  description: string;
  order: number;
  tags: string[];
  keywords: string[];
  breadcrumbTitle?: string;
}): string[] {
  const overlap = fields.tags.filter((tag) => fields.keywords.includes(tag));
  if (overlap.length) throw new Error(`"${fields.label}" repeats ${overlap.join(', ')} in tags and keywords`);
  return [
    '---',
    `label: ${JSON.stringify(fields.label)}`,
    `description: ${JSON.stringify(fields.description)}`,
    `order: ${fields.order}`,
    `tags: ${yamlList(fields.tags)}`,
    `keywords: ${yamlList(fields.keywords)}`,
    ...(fields.breadcrumbTitle ? [`breadcrumbTitle: ${JSON.stringify(fields.breadcrumbTitle)}`] : []),
    '---',
    '',
    GENERATED_MARKER,
    '',
  ];
}

function table(header: string[], rows: string[][]): string[] {
  return [
    `| ${header.join(' | ')} |`,
    `|${header.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ];
}

/** `color: #abc; font-weight: bold` → `{ color: '#abc', 'font-weight': 'bold' }`. */
function declarations(value: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const part of value.split('; ')) {
    const index = part.indexOf(': ');
    if (index > 0) result[part.slice(0, index)] = part.slice(index + 2);
  }
  return result;
}

function fontStyle(decls: Record<string, string>): string {
  const parts = [decls['font-weight'], decls['font-style'], decls['text-decoration']?.split(' ')[0]].filter(
    (part): part is string => !!part && part !== 'normal' && part !== 'none',
  );
  return parts.length ? parts.join(', ') : '-';
}

async function collect(id: string): Promise<ThemeDoc> {
  const pkg = JSON.parse(fs.readFileSync(path.join(repoRoot, 'packages', id, 'package.json'), 'utf8')) as {
    name: string;
    description: string;
  };
  const loaded = await loadTheme(id);
  const css = editorCss(loaded.extension);
  const surfaces = themeSurfaces(loaded.extension);
  const foreground = colorOf(ruleFor(css, '&'), 'color');
  if (!surfaces || !foreground) throw new Error(`Theme "${id}" has no opaque background or text color`);
  return {
    id,
    title: TITLE_OVERRIDES[id] ?? pkg.description.replace(/ theme for the CodeMirror editor$/, ''),
    npmName: pkg.name,
    exportName: loaded.exportName,
    dark: editorState(loaded.extension).facet(EditorView.darkTheme),
    family: FAMILIES.find(([prefix]) => id.startsWith(`${prefix}-`))?.[1],
    extension: loaded.extension,
    css,
    foreground,
    surfaces,
    highlights: resolvedHighlights(loaded.extension),
    mergeStyles: loaded.module[`${loaded.exportName}MergeStyles`] as Record<string, string>,
  };
}

/** Lowest contrast of the default text and of every syntax color over the background, active line and selection. */
function lowestTextContrast(doc: ThemeDoc): { ratio: number; surface: string } {
  const colors = new Map<string, Rgba>([[toHex(doc.foreground), doc.foreground]]);
  for (const value of Object.values(doc.highlights)) {
    const color = prop(declarations(value), 'color');
    const parsed = color ? parseColor(color) : undefined;
    if (parsed) colors.set(`${toHex(parsed)}/${parsed[3]}`, parsed);
  }
  let lowest = { ratio: Number.POSITIVE_INFINITY, surface: 'background' };
  for (const color of colors.values()) {
    for (const [name, rgba] of doc.surfaces) {
      const ratio = contrastRatio(color, rgba);
      if (ratio < lowest.ratio) lowest = { ratio, surface: name };
    }
  }
  return lowest;
}

/** Lowest contrast of a color against the given surfaces. */
function lowestOn(color: Rgba | undefined, surfaces: Rgba[]): number | undefined {
  return color ? Math.min(...surfaces.map((rgba) => contrastRatio(color, rgba))) : undefined;
}

interface UiMeasure {
  element: string;
  selector: string;
  value: string | undefined;
  against: string;
  ratio: number | undefined;
  min: number;
}

/** The UI indicators the contrast tests check, measured the same way (see tests/support/wcag.ts). */
function uiMeasures(doc: ThemeDoc): UiMeasure[] {
  const { css } = doc;
  const background = doc.surfaces[0][1];
  const activeLine = surface(doc, 'active-line');
  const lineSurfaces = activeLine ? [background, activeLine] : [background];
  const lineLabel = activeLine ? 'background, active line' : 'background';

  const gutters = ruleFor(css, '.cm-gutters');
  const gutterText = colorOf(gutters, 'color');
  const gutterBg = colorOf(gutters, 'background-color');
  const gutterSurface = gutterBg ? composite(gutterBg, background) : background;

  const cursor = ruleFor(css, '.cm-cursor')?.['border-left-color'];
  const ring = focusRings(ruleFor(css, '&.cm-focused')?.['box-shadow'])
    .filter((layer) => layer.width >= 2)
    .map((layer) => ({ color: layer.color, ratio: contrastRatio(layer.color, background) }))
    .sort((a, b) => b.ratio - a.ratio)[0];
  const bracket = ruleFor(css, '.cm-matchingBracket');
  const selected = ruleFor(css, '.cm-searchMatch.cm-searchMatch-selected');
  const fill = colorOf(selected, 'background-color');
  const outline = outlineColor(selected);
  const searchRatio = Math.max(
    fill ? contrastRatio(fill, background) : 0,
    outline ? contrastRatio(outline, background) : 0,
  );

  return [
    {
      element: 'Text',
      selector: '&',
      value: toHex(doc.foreground),
      against: 'background, active line, selection',
      ratio: lowestOn(
        doc.foreground,
        doc.surfaces.map(([, rgba]) => rgba),
      ),
      min: TEXT_MIN,
    },
    {
      element: 'Line numbers',
      selector: '.cm-gutters',
      value: prop(gutters, 'color'),
      against: 'gutter',
      ratio: lowestOn(gutterText, [gutterSurface]),
      min: TEXT_MIN,
    },
    {
      element: 'Cursor',
      selector: '.cm-cursor',
      value: cursor,
      against: lineLabel,
      ratio: lowestOn(cursor ? parseColor(cursor) : undefined, lineSurfaces),
      min: NON_TEXT_MIN,
    },
    {
      element: 'Focus ring',
      selector: '&.cm-focused',
      value: ring ? toHex(ring.color) : undefined,
      against: 'background',
      ratio: ring?.ratio,
      min: NON_TEXT_MIN,
    },
    {
      element: 'Matching bracket outline',
      selector: '.cm-matchingBracket',
      value: prop(bracket, 'outline'),
      against: lineLabel,
      ratio: lowestOn(outlineColor(bracket), lineSurfaces),
      min: NON_TEXT_MIN,
    },
    {
      element: 'Current search match',
      selector: '.cm-searchMatch-selected',
      value: [prop(selected, 'background-color'), prop(selected, 'outline')].filter(Boolean).join(', ') || undefined,
      against: 'background (fill or outline)',
      ratio: searchRatio || undefined,
      min: NON_TEXT_MIN,
    },
    {
      element: 'Selection',
      selector: '.cm-selectionBackground',
      value: ruleFor(css, '.cm-selectionBackground')?.['background-color'],
      against: 'active line',
      ratio: selectionOnActiveLineRatio(doc.extension),
      min: SELECTION_ON_ACTIVE_LINE_MIN,
    },
  ];
}

function themePage(doc: ThemeDoc, order: number): string {
  const npm = doc.npmName;
  const surfacesHeader = doc.surfaces.map(([name]) => `On ${(SURFACE_LABELS[name] ?? name).toLowerCase()}`);
  const syntaxRows = SYNTAX_ROWS.map(([label, key]) => {
    const decls = declarations(doc.highlights[key] ?? '');
    const colorValue = prop(decls, 'color');
    const color = colorValue ? parseColor(colorValue) : undefined;
    const text = color ?? doc.foreground;
    return [
      label,
      code(key),
      colorValue ? code(colorValue) : `inherits ${code(toHex(doc.foreground))}`,
      fontStyle(decls),
      ...doc.surfaces.map(([, rgba]) => formatRatio(contrastRatio(text, rgba))),
    ];
  });
  const ui = uiMeasures(doc);
  const lowest = lowestTextContrast(doc);
  const family = doc.family ? ` It belongs to the ${doc.family} family.` : '';
  const added = NEW_THEMES.has(doc.id) ? ' Added in 6.31.0.' : '';

  return [
    ...frontmatter({
      label: doc.title,
      description: `${doc.title}, a ${mode(doc).toLowerCase()} CodeMirror 6 theme: install, usage, syntax and editor colors with WCAG contrast ratios.`,
      order,
      tags: ['themes', doc.id, mode(doc).toLowerCase()],
      keywords: [npm, doc.exportName === doc.id ? `${doc.exportName}MergeStyles` : doc.exportName, 'wcag contrast'],
    }),
    `# ${doc.title}`,
    '',
    `[![npm version](https://img.shields.io/npm/v/${npm})](https://www.npmjs.com/package/${npm})`,
    `[![npm downloads](https://img.shields.io/npm/dt/${npm})](https://www.npmjs.com/package/${npm})`,
    '',
    `${doc.title} is a **${mode(doc).toLowerCase()}** CodeMirror 6 theme whose text colors all meet WCAG AA contrast.` +
      `${family}${added}`,
    '',
    ...(THEME_NOTES[doc.id] ? [...THEME_NOTES[doc.id], ''] : []),
    `[Open in playground](${PLAYGROUND}/theme-gallery/) to compare it with the other themes.`,
    '',
    '## Install',
    '',
    '```bash',
    `npm install ${npm} codemirror`,
    '```',
    '',
    `The theme is also exported as \`${doc.exportName}\` by \`@fsegurai/codemirror-theme-bundle\`.`,
    '',
    '## Usage',
    '',
    '```ts',
    "import { basicSetup, EditorView } from 'codemirror';",
    `import { ${doc.exportName} } from '${npm}';`,
    '',
    'new EditorView({',
    "  doc: 'const answer = 42;',",
    `  extensions: [basicSetup, ${doc.exportName}],`,
    '  parent: document.body,',
    '});',
    '```',
    '',
    '| Export | Type |',
    '|---|---|',
    `| \`${doc.exportName}\` | \`Extension\` |`,
    `| \`${doc.exportName}MergeStyles\` | \`IMergeRevertStyles\` |`,
    '| `applyMergeRevertStyles` | `(styles: IMergeRevertStyles) => void` |',
    '',
    '## Editor surfaces',
    '',
    'Translucent colors are composited over the background, which is the color text is measured against.',
    '',
    ...table(
      ['Surface', 'Color'],
      doc.surfaces.map(([name, rgba]) => [SURFACE_LABELS[name] ?? name, code(toHex(rgba))]),
    ),
    '',
    '## Syntax colors',
    '',
    `Resolved highlight styles for common [Lezer tags](https://lezer.codemirror.net/docs/ref/#highlight.tags) and their ` +
      `contrast ratio. WCAG AA requires ${TEXT_MIN}:1 for text; the lowest ratio of this theme, over all tags, is ` +
      `${formatRatio(lowest.ratio)} on the ${(SURFACE_LABELS[lowest.surface] ?? lowest.surface).toLowerCase()}.`,
    '',
    ...table(['Role', 'Tag', 'Color', 'Style', ...surfacesHeader], syntaxRows),
    '',
    '## Editor UI colors',
    '',
    `Non-text indicators need ${NON_TEXT_MIN}:1 (WCAG 1.4.11). The selection must stay distinguishable on the active ` +
      `line (${SELECTION_ON_ACTIVE_LINE_MIN}:1 or more).`,
    '',
    ...table(
      ['Element', 'Selector', 'Color', 'Measured against', 'Ratio', 'Result'],
      ui.map((m) => [
        m.element,
        code(m.selector),
        m.value ? code(m.value) : '-',
        m.against,
        m.ratio === undefined ? '-' : formatRatio(m.ratio),
        verdict(m.ratio, m.min),
      ]),
    ),
    '',
    '## Merge view colors',
    '',
    `Values of \`${doc.exportName}MergeStyles\`, for [\`applyMergeRevertStyles\`](../api/merge-styles.md).`,
    '',
    ...table(
      ['Field', 'Value'],
      Object.keys(doc.mergeStyles)
        .sort()
        .map((key) => [code(key), code(doc.mergeStyles[key])]),
    ),
    '',
    '## See also',
    '',
    '- [Theme catalog](README.md)',
    '- [Accessibility](../accessibility/README.md) and the [contrast summary](../accessibility/contrast-summary.md)',
    '- [Styling Merge Views](../guides/merge-views.md)',
    '',
  ].join('\n');
}

function catalogPage(docs: ThemeDoc[]): string {
  const dark = docs.filter((doc) => doc.dark).length;
  const families = new Map<string, ThemeDoc[]>();
  for (const doc of docs) {
    const key = doc.family ?? (doc.dark ? 'Standalone dark themes' : 'Standalone light themes');
    families.set(key, [...(families.get(key) ?? []), doc]);
  }
  const familyRows = [...families]
    .sort(
      ([a], [b]) => (a.startsWith('Standalone') ? 1 : 0) - (b.startsWith('Standalone') ? 1 : 0) || a.localeCompare(b),
    )
    .map(([name, members]) => [name, members.map((doc) => `[${doc.title}](${doc.id}.md)`).join(', ')]);
  const newThemes = docs.filter((doc) => NEW_THEMES.has(doc.id));

  return [
    ...frontmatter({
      label: 'Themes',
      description: `Catalog of all ${docs.length} themes with package names, export names, light or dark mode and editor colors.`,
      order: THEMES_SECTION_ORDER,
      tags: ['themes', 'catalog'],
      keywords: ['packages', 'exports', 'light', 'dark'],
      breadcrumbTitle: 'Themes',
    }),
    '# Themes',
    '',
    `This release ships **${docs.length} themes**: ${dark} dark and ${docs.length - dark} light. Every theme is ` +
      'available as its own package and from `@fsegurai/codemirror-theme-bundle` under the same export name, and every ' +
      'theme meets WCAG AA text contrast (see [Accessibility](../accessibility/README.md)).',
    '',
    `[Open in playground](${PLAYGROUND}/theme-gallery/) to see every theme side by side.`,
    '',
    '## Catalog',
    '',
    ...table(
      ['Theme', 'Package', 'Extension export', 'Mode', 'Background', 'Text'],
      docs.map((doc) => [
        `[${doc.title}](${doc.id}.md)`,
        code(doc.npmName),
        code(doc.exportName),
        mode(doc),
        code(toHex(doc.surfaces[0][1])),
        code(toHex(doc.foreground)),
      ]),
    ),
    '',
    'Each package also exports `<extension>MergeStyles` (for example `nordMergeStyles`) and `applyMergeRevertStyles`. ' +
      'See the [API reference](../api/README.md).',
    '',
    '## New in 6.31.0',
    '',
    ...newThemes.map((doc) => `- [${doc.title}](${doc.id}.md) (${mode(doc).toLowerCase()}, \`${doc.exportName}\`)`),
    '',
    'See [What is new in 6.31.0](../releases/6.31.0.md) for the color changes of the existing themes.',
    '',
    '## Families',
    '',
    ...table(['Family', 'Themes'], familyRows),
    '',
    '## Live demo',
    '',
    'Try every theme on Markdown, a side-by-side merge view and a unified diff in the',
    '[live playground](https://fsegurai.github.io/codemirror-themes/playground.html).',
    '',
  ].join('\n');
}

function contrastSummaryPage(docs: ThemeDoc[]): string {
  const rows = docs.map((doc) => {
    const lowest = lowestTextContrast(doc);
    const ui = new Map(uiMeasures(doc).map((m) => [m.element, m]));
    const cell = (element: string) => {
      const ratio = ui.get(element)?.ratio;
      return ratio === undefined ? '-' : formatRatio(ratio);
    };
    const pass = themeFailures(doc.extension).length === 0 && nonTextFailures(doc.extension).length === 0;
    return [
      `[${doc.title}](../themes/${doc.id}.md)`,
      mode(doc),
      `${formatRatio(lowest.ratio)} (${(SURFACE_LABELS[lowest.surface] ?? lowest.surface).toLowerCase()})`,
      cell('Line numbers'),
      cell('Cursor'),
      cell('Focus ring'),
      cell('Matching bracket outline'),
      cell('Selection'),
      pass ? 'Pass' : 'Fail',
    ];
  });
  return [
    ...frontmatter({
      label: 'Contrast Summary',
      description: `Lowest WCAG contrast ratios of all ${docs.length} themes for text, line numbers, cursor, focus ring, brackets and selection.`,
      order: CONTRAST_SUMMARY_ORDER,
      tags: ['accessibility', 'contrast', 'summary'],
      keywords: ['wcag 2.2', 'contrast ratio', 'non-text contrast', 'themes table'],
    }),
    '# Contrast Summary',
    '',
    'Lowest contrast ratio per theme, measured on the rendered editor CSS with the same code as the contrast tests.',
    '',
    `- **Lowest text**: the default text and every syntax color against the background, the active line and the ` +
      `selection (minimum ${TEXT_MIN}:1).`,
    `- **Line numbers**: gutter text against the gutter background (minimum ${TEXT_MIN}:1).`,
    `- **Cursor**, **Focus ring**, **Bracket**: non-text indicators against the background and the active line ` +
      `(minimum ${NON_TEXT_MIN}:1).`,
    `- **Selection**: the selection against the active line, so a selection on the current line stays visible ` +
      `(minimum ${SELECTION_ON_ACTIVE_LINE_MIN}:1).`,
    '',
    ...table(
      ['Theme', 'Mode', 'Lowest text', 'Line numbers', 'Cursor', 'Focus ring', 'Bracket', 'Selection', 'AA'],
      rows,
    ),
    '',
    `Each theme page lists the full color tables. [Open in playground](${PLAYGROUND}/contrast-inspector/) to measure ` +
      'any color pair yourself.',
    '',
  ].join('\n');
}

function write(file: string, content: string): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) return;
  fs.writeFileSync(file, content, 'utf8');
  console.log('Wrote', path.relative(repoRoot, file));
}

async function main(): Promise<void> {
  const version = docsVersion();
  const contentDir = path.join(docsRoot, version, 'content');
  if (!fs.existsSync(contentDir)) throw new Error(`Missing ${path.relative(repoRoot, contentDir)}`);

  const docs: ThemeDoc[] = [];
  for (const id of themeIds()) docs.push(await collect(id));
  docs.sort((a, b) => a.title.localeCompare(b.title, 'en'));

  const themesDir = path.join(contentDir, 'themes');
  const expected = new Set(['README.md', ...docs.map((doc) => `${doc.id}.md`)]);
  write(path.join(themesDir, 'README.md'), catalogPage(docs));
  docs.forEach((doc, index) => {
    write(path.join(themesDir, `${doc.id}.md`), themePage(doc, THEMES_SECTION_ORDER + 1 + index));
  });
  write(path.join(contentDir, 'accessibility', 'contrast-summary.md'), contrastSummaryPage(docs));

  // Remove pages this script generated earlier for packages that no longer exist.
  for (const name of fs.readdirSync(themesDir).sort()) {
    const file = path.join(themesDir, name);
    if (expected.has(name) || !name.endsWith('.md')) continue;
    if (fs.readFileSync(file, 'utf8').includes(GENERATED_MARKER)) {
      fs.rmSync(file);
      console.log('Removed', path.relative(repoRoot, file));
    }
  }
  console.log(`Theme docs up to date for docs/${version} (${docs.length} themes).`);
}

await main();
