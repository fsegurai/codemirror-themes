/// <reference types="bun" />
/**
 * Generates the theme pages of the versioned documentation from the theme package sources:
 *
 * - `docs/<version>/content/themes/README.md`: catalog of every theme package.
 * - `docs/<version>/content/themes/<id>.md`: one page per theme (install, usage, syntax and UI colors with WCAG
 *   contrast ratios, merge styles).
 * - `docs/<version>/content/accessibility/contrast-summary.md`: one contrast row per theme.
 *
 * Colors are read from the rendered CSS of each theme extension with the helpers the contrast tests use, so the
 * documented ratios are the ratios the tests enforce. The output is deterministic: running it twice changes nothing.
 *
 * Usage: `bun run generate:theme-docs [--version <x.y.z>]`. Without `--version` the newest `docs/<x.y.z>/` folder is
 * used.
 */
